_ARTICLE = re.compile(r"^(第\d+條(?:第\d+項)?)")


def classify(law: str) -> str | None:
    """條文字串 → 類別。對不到回 None（呼叫端必須報錯，不可靜默丟進其他行政）。"""
    if not law:
        return None
    law = law.strip()
    m = _ARTICLE.match(law)
    head = m.group(1) if m else ""
    body = law[len(head):].strip(" -－—") if m else law

    for category, keywords in TEXT_RULES:
        if any(k in body for k in keywords):
            return category

    if head:
        if head in ARTICLE_RULES:                  # 先試「條+項」
            return ARTICLE_RULES[head]
        article = head.split("第", 2)[1] if head.count("第") > 1 else None
        base = "第" + head.split("條")[0].lstrip("第") + "條"
        if base in ARTICLE_RULES:                  # 再退回「條」
            return ARTICLE_RULES[base]

    # 無條號者（如「經營許可設立以外之業務」）已由 TEXT_RULES 攔下
    return None


def assert_all_classified(records, law_field="law"):
    """每一筆都必須對到類別。未命中要當場報錯——靜默丟進「其他行政」
    會把 severity 5 的案子算成 1 分，是會影響排序的沉默失敗。"""
    unmapped = sorted({r[law_field] for r in records if not classify(r.get(law_field))})
    assert not unmapped, (
        f"有 {len(unmapped)} 種條文對不到類別，請補進 etl/categories.py："
        + "\n  ".join([""] + unmapped[:20])
    )
